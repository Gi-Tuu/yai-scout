"""Build the Track A external benchmark from official PyPI release timestamps.

Only the dev split is generated by default. All facts come from the public PyPI
JSON API and are frozen into local snapshots.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import urllib.request
from datetime import UTC, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")


def _fetch(url: str, cache: Path) -> dict:
    if cache.exists():
        return json.loads(cache.read_text(encoding="utf-8"))
    with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310
        payload = json.loads(response.read().decode("utf-8"))
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
    return payload


def _release_times(payload: dict) -> list[tuple[str, datetime]]:
    releases: dict[str, list[dict]] = payload.get("releases", {})
    result: list[tuple[str, datetime]] = []
    for version, files in releases.items():
        if not VERSION_RE.fullmatch(version) or not files:
            continue
        timestamps = []
        for item in files:
            raw = item.get("upload_time_iso_8601") or item.get("upload_time")
            if not raw:
                continue
            try:
                timestamps.append(datetime.fromisoformat(raw.replace("Z", "+00:00")))
            except ValueError:
                continue
        if timestamps:
            result.append((version, min(timestamps).astimezone(UTC)))
    return sorted(result, key=lambda item: item[1])


def _snapshot_text(package: str, versions: list[tuple[str, datetime]]) -> str:
    latest = versions[-1][0]
    lines = [f"Package: {package}", f"Latest version: {latest}", "Version history:"]
    lines.extend(
        f"{version} | {published.date().isoformat()}" for version, published in versions
    )
    return "\n".join(lines) + "\n"


def build(packages: list[str], pairs: int, snapshots_dir: Path) -> list[dict]:
    cases: list[dict] = []
    for package in packages:
        cache = ROOT / "benchmarks" / "external_v1" / "cache" / f"{package}.json"
        payload = _fetch(f"https://pypi.org/pypi/{package}/json", cache)
        releases = _release_times(payload)
        if len(releases) < pairs + 1:
            continue
        for index in range(pairs):
            base_version, base_time = releases[index]
            next_version, next_time = releases[index + 1]
            fresh_as_of = base_time.date()
            stale_as_of = (next_time + timedelta(days=1)).date()
            if fresh_as_of >= next_time.date() or stale_as_of <= next_time.date():
                continue
            for kind, as_of, support, status in (
                ("fresh", fresh_as_of, "supports", "fresh"),
                ("stale", stale_as_of, "contradicts", "stale"),
            ):
                case_id = f"ext_{package}_{index}_{kind}"[:80]
                visible = [item for item in releases if item[1].date() <= as_of]
                current = visible[-1][0]
                text = _snapshot_text(package, visible)
                snapshot = snapshots_dir / f"{case_id}.txt"
                snapshot.write_text(text, encoding="utf-8")
                cases.append({
                    "id": case_id,
                    "split": "dev",
                    "source_family": f"pypi:{package}",
                    "claim_text": f"{package} 当前版本是 {base_version}",
                    "claim_type": "version",
                    "as_of": as_of.isoformat(),
                    "gold_status": status,
                    "gold_current_value": current,
                    "gold_support": support,
                    "evidence": [{
                        "url": f"https://pypi.org/project/{package}/#history",
                        "published_at": visible[-1][1].date().isoformat(),
                        "content_hash": "sha256:" + hashlib.sha256(
                            text.encode("utf-8")
                        ).hexdigest(),
                        "snapshot_path": str(
                            snapshot.relative_to(ROOT / "benchmarks" / "external_v1")
                        ),
                    }],
                    "notes": f"official PyPI timestamps; as_of={as_of.isoformat()}",
                })
    return cases


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--packages",
        default="fastapi,requests,django,numpy,pytest",
    )
    parser.add_argument("--pairs", type=int, default=4)
    args = parser.parse_args(argv)
    output = ROOT / "benchmarks" / "external_v1"
    snapshots = output / "snapshots"
    snapshots.mkdir(parents=True, exist_ok=True)
    cases = build(
        [item.strip() for item in args.packages.split(",") if item.strip()],
        args.pairs,
        snapshots,
    )
    if not cases:
        raise SystemExit("no cases generated; check network/cache")
    dev = output / "dev.jsonl"
    dev.write_text(
        "\n".join(json.dumps(case, ensure_ascii=False) for case in cases) + "\n",
        encoding="utf-8",
    )
    manifest = {
        "version": "external-v1",
        "split": "dev",
        "cases": len(cases),
        "source_families": sorted({case["source_family"] for case in cases}),
        "dev_hash": hashlib.sha256(dev.read_bytes()).hexdigest(),
        "snapshot_hash": hashlib.sha256(
            b"".join(path.read_bytes() for path in sorted(snapshots.glob("*.txt")))
        ).hexdigest(),
        "generated_at": datetime.now(UTC).isoformat(),
        "source": "PyPI JSON API",
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"cases={len(cases)} dev={dev.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
